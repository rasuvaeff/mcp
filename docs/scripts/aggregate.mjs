import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptsDir = dirname(fileURLToPath(import.meta.url))
const docsDir = join(scriptsDir, '..')
const pkgDir = join(docsDir, '..')

const REPO_BLOB = 'https://github.com/rasuvaeff/mcp/blob/master/'

function rewriteRelativeLinks(markdown) {
    return markdown.replace(/\]\((?!https?:|#|\/)([^)]+)\)/g, (_match, target) => `](${REPO_BLOB}${target})`)
}

// llms.txt is the single source of truth — import it whole.
const directImports = [
    {
        source: 'llms.txt',
        file: 'llms.md',
        title: 'llms.txt reference',
        description: 'A compact, LLM-friendly API reference for rasuvaeff/mcp — paste it into an AI coding assistant for accurate MCP server code.',
    },
]

for (const entry of directImports) {
    const raw = readFileSync(join(pkgDir, entry.source), 'utf8')
    const body = rewriteRelativeLinks(raw)
    const outPath = join(docsDir, entry.file)
    mkdirSync(dirname(outPath), { recursive: true })
    writeFileSync(
        outPath,
        `---\ntitle: ${JSON.stringify(entry.title)}\ndescription: ${JSON.stringify(entry.description)}\n---\n\n` +
            `<!-- AUTO-GENERATED by docs/scripts/aggregate.mjs from ${entry.source} — do not edit this file directly. -->\n\n` +
            body.trimStart() +
            '\n',
        'utf8',
    )
}

console.log(`Imported ${directImports.length} source file(s) whole into docs/**.`)
